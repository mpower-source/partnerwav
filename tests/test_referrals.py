    rid = card.get_attribute("data-ref-row")
    pg.click("[data-ref-new]"); pg.wait_for_timeout(200)
    pg.select_option("#rfHouse", pg.locator("#rfHouse option").filter(has_text="Seven Peaks").get_attribute("value"))
