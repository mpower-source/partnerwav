    pg.click('[data-ref-view="ref-demo-1"]'); pg.wait_for_timeout(250)
    v = pg.inner_text("#referralViewContent")
    ok("฿80,000" in v and "฿56,000" in v and "฿24,000" in v and "฿28,000" in v, "Fee: 10% of ฿800k collected = ฿80k; partner 70% = ฿56k; CloudWAV ฿24k; ฿28k paid out")

