    ok(pg.locator("[data-house-row]").count() == 2 and "Referral 8%" in pg.inner_text("#referralsContent"), "Seven Peaks added as a referral partner with its own rate")
    nav(pg, "operator-msp-prospects")
    ok("Referral partner ✓" in pg.locator('[data-msp-card="sw-sevenpeakssoftware"]').inner_text(), "Prospect card shows it's a referral partner")
    nav(pg, "operator-agreements")
    ok(pg.locator("[data-agr-row]").filter(has_text="Seven Peaks").count() == 1, "Draft referral agreement created for Seven Peaks")

