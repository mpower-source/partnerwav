from harness import *
with sync_playwright() as p:
    b, pg = open_page(p)
    role(pg, "partner"); nav(pg, "partner-messages")
    items = pg.locator("#msgList [data-open-convo]")
    ok(items.count() == 4, "Demo partner has 4 conversations")
    ok(pg.locator("#msgList .unread-dot").count() >= 1, "Unread marker on new replies")
    ok(items.first.inner_text().startswith("PL") or "Portonics" in items.first.inner_text(), "Most recent conversation first")
    pg.locator("#msgList [data-open-convo]").filter(has_text="Intelsense").click(); pg.wait_for_timeout(200)
    ok("rate-limit" in pg.inner_text("#msgThreadBody") and "VENDOR" in pg.inner_text("#msgThreadHeader").upper(), "Vendor conversation opens with history")
    pg.fill("#msgCompose", "Thanks -- branch 3 next week."); pg.click("#msgSendBtn"); pg.wait_for_timeout(200)
    ok("branch 3 next week" in pg.inner_text("#msgThreadBody"), "Sent message appears")
    # the vendor side of the same conversation
    role(pg, "vendor"); nav(pg, "partner-messages")
    v = " | ".join(pg.locator("#msgList [data-open-convo]").all_inner_texts())
    ok("Siam Digital MSP" in v and "branch 3 next week" in v and "Portonics" not in v, "Vendor sees the partner's message in the same conversation, not others'")
    # start a conversation from the network
    role(pg, "partner"); nav(pg, "partner-network")
    btn = pg.locator('[data-message-partner="Riverside Telco"]:visible')
    if btn.count():
        btn.first.click(); pg.wait_for_timeout(300)
        ok(visible_screen(pg) == ["scr-partner-messages"] and "Riverside Telco" in pg.inner_text("#msgThreadHeader"), "Message button opens that conversation")
    pg.select_option("#msgNewTo", "operator:"); pg.wait_for_timeout(250)
    ok("PartnerWAV" in pg.inner_text("#msgThreadHeader"), "New message to CloudWAV")
    pg.fill("#msgCompose", "Hello CloudWAV"); pg.click("#msgSendBtn"); pg.wait_for_timeout(200)
    role(pg, "operator"); nav(pg, "partner-messages")
    o = " | ".join(pg.locator("#msgList [data-open-convo]").all_inner_texts())
    ok("Hello CloudWAV" in o and "branch 3" not in o, "Operator inbox has messages to CloudWAV only")
    role(pg, "affiliate")
    ok(in_menu(pg, "partner-messages"), "Affiliates have Messages too")
    pg.reload(); pg.wait_for_timeout(700); role(pg, "partner"); nav(pg, "partner-messages")
    ok("Hello CloudWAV" in pg.inner_text("#msgList"), "Messages persist (demo: this browser)")
    pg.set_viewport_size({"width": 390, "height": 844}); pg.wait_for_timeout(200)
    ok(pg.evaluate("document.documentElement.scrollWidth-innerWidth") <= 0, "Fits at 390px")
    b.close()
report()
